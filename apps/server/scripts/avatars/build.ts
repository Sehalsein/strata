// Renders Strata's profile pictures (characters.ts) to PNG and writes
// src/avatars/catalog.generated.ts, which the server bundles and serves at /api/avatars.
//   bun scripts/avatars/build.ts [--sheet <file.png>]   (--sheet: a contact sheet to look at)
import { Resvg } from "@resvg/resvg-js";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { characters, groups, svgFor } from "./characters";

const SIZE = 384;

const grouped = groups.flatMap((g) => g.ids);
const missing = characters.filter((c) => !grouped.includes(c.id)).map((c) => c.id);
if (missing.length || new Set(grouped).size !== characters.length) throw new Error(`Every character goes in exactly one group (not grouped: ${missing.join(", ") || "none"})`);

const rendered = characters.map((c) => {
  const png = new Resvg(svgFor(c), { fitTo: { mode: "width", value: SIZE } }).render().asPng();
  return { ...c, png: Buffer.from(png) };
});

const out = join(import.meta.dir, "../../src/avatars/catalog.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/avatars/build.ts from scripts/avatars/characters.ts. Don't edit.
// Original characters drawn for Strata, ${SIZE}×${SIZE} PNG.
export const AVATAR_SIZE = ${SIZE};
export const avatarGroups: { title: string; ids: string[] }[] = ${JSON.stringify(groups)};
export const avatarCatalog: { id: string; name: string; background: string; png: string }[] = [
${rendered.map((c) => `  { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)}, background: ${JSON.stringify(c.background)}, png: ${JSON.stringify(c.png.toString("base64"))} },`).join("\n")}
];
`,
);
const bytes = rendered.reduce((n, c) => n + c.png.length, 0);
console.log(`${rendered.length} avatars, ${(bytes / 1024).toFixed(0)} KB of PNG → ${out}`);

// A contact sheet, 6 across, to check them by eye.
const sheetArg = process.argv.indexOf("--sheet");
if (sheetArg > 0) {
  const cols = 6;
  const cell = 160;
  const rows = Math.ceil(characters.length / cols);
  const cells = characters
    .map((c, i) => {
      const x = (i % cols) * cell + 8;
      const y = Math.floor(i / cols) * cell + 8;
      const inner = svgFor(c).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
      return `<g transform="translate(${x} ${y})"><clipPath id="c${i}"><circle cx="72" cy="72" r="72"/></clipPath><g clip-path="url(#c${i})"><g transform="scale(${144 / 256})">${inner}</g></g><text x="72" y="160" text-anchor="middle" font-family="Helvetica" font-size="13" fill="#ddd">${c.name}</text></g>`;
    })
    .join("");
  const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${cols * cell}" height="${rows * cell + 12}"><rect width="100%" height="100%" fill="#111318"/>${cells}</svg>`;
  writeFileSync(process.argv[sheetArg + 1]!, new Resvg(sheet).render().asPng());
  console.log(`Contact sheet → ${process.argv[sheetArg + 1]}`);
}
