// Generates an Ed25519 keypair for signing update manifests.
//
//   bun scripts/keygen.ts                                  # print both halves
//   bun scripts/keygen.ts --private-out ~/strata-update.key --write-public
//
// The PUBLIC key is compiled into every server binary (src/update/publicKey.ts) and is safe to
// commit. The PRIVATE key signs release manifests: keep it out of the repo (a CI secret named
// STRATA_UPDATE_PRIVATE_KEY once release CI exists, plus an offline backup). Never commit it.
//
// Rotating keys: servers only trust the key they were built with, so publish one release
// signed with the OLD key whose binary embeds the NEW public key, then switch the secret.
import { generateKeyPairSync } from "node:crypto";
import { chmodSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const args = process.argv.slice(2);
const flag = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const publicB64 = publicKey.export({ format: "der", type: "spki" }).toString("base64");
const privateB64 = privateKey.export({ format: "der", type: "pkcs8" }).toString("base64");

const privateOut = flag("--private-out");
if (privateOut) {
  writeFileSync(resolve(privateOut), privateB64 + "\n", { mode: 0o600 });
  chmodSync(resolve(privateOut), 0o600);
}

if (args.includes("--write-public")) {
  const file = join(import.meta.dir, "..", "src", "update", "publicKey.ts");
  writeFileSync(
    file,
    `// Ed25519 public key (base64 SPKI DER) that update manifests must be signed with.
// Generated by scripts/keygen.ts. The private half is never committed (see README → Updates).
export const UPDATE_PUBLIC_KEY = "${publicB64}";
`,
  );
  console.log(`Wrote the public key to ${file}`);
}

console.log(`
Public key (base64 SPKI DER) — commit it in src/update/publicKey.ts (--write-public does that):

  ${publicB64}
`);
if (privateOut) {
  console.log(`Private key written to ${resolve(privateOut)} (mode 600).`);
} else {
  console.log(`Private key (base64 PKCS#8 DER) — KEEP SECRET, do not commit:

  ${privateB64}
`);
}
console.log(`
Next steps:
  1. Keep the private key where releases are signed (scripts/release-manifest.ts reads it from
     STRATA_UPDATE_PRIVATE_KEY or --key-file; one line of base64, a PEM block works too).
     When release CI exists it becomes a CI secret of the same name.
  2. Keep an offline backup of the private key. Losing it means existing servers can't
     verify future updates (they would need a manual reinstall).
  3. Rebuild and release so binaries embed the new public key.
`);
